// Safe bridge between the UI (renderer) and the native main process.
const { contextBridge, ipcRenderer } = require("electron");

contextBridge.exposeInMainWorld("api", {
  // --- Existing ---
  pickFolder: () => ipcRenderer.invoke("pick-folder"),
  pickMainFolder: () => ipcRenderer.invoke("pick-main-folder"),
  getSettings: () => ipcRenderer.invoke("get-settings"),
  setMainFolder: (p) => ipcRenderer.invoke("set-main-folder", p),
  setLang: (lang) => ipcRenderer.invoke("set-lang", lang),
  listFolders: () => ipcRenderer.invoke("list-folders"),
  createFolder: (name) => ipcRenderer.invoke("create-folder", name),
  renameFolder: (args) => ipcRenderer.invoke("rename-folder", args),
  removeFolder: (name) => ipcRenderer.invoke("remove-folder", name),
  getFavorites: () => ipcRenderer.invoke("get-favorites"),
  addFavorite: () => ipcRenderer.invoke("add-favorite"),
  removeFavorite: (p) => ipcRenderer.invoke("remove-favorite", p),
  openFavorite: (p) => ipcRenderer.invoke("open-favorite", p),
  togglePin: (id) => ipcRenderer.invoke("toggle-pin", id),
  getInfo: (url) => ipcRenderer.invoke("get-info", url),
  fetchPlaylist: (url) => ipcRenderer.invoke("fetch-playlist", url),
  checkDuplicate: (opts) => ipcRenderer.invoke("check-duplicate", opts),
  download: (opts) => ipcRenderer.invoke("download", opts),
  cancelDownload: () => ipcRenderer.invoke("cancel-download"),
  setPreventDuplicates: (val) => ipcRenderer.invoke("set-prevent-duplicates", val),
  setAutoTag: (v) => ipcRenderer.invoke("set-auto-tag", v),
  setAudioFormat: (v) => ipcRenderer.invoke("set-audio-format", v),
  setAudioBitrate: (v) => ipcRenderer.invoke("set-audio-bitrate", v),
  setLoudnorm: (v) => ipcRenderer.invoke("set-loudnorm", v),
  setLufs: (v) => ipcRenderer.invoke("set-lufs", v),
  setSuggestFolder: (v) => ipcRenderer.invoke("set-suggest-folder", v),
  setCookiesBrowser: (b) => ipcRenderer.invoke("set-cookies-browser", b),
  setFolderView: (v) => ipcRenderer.invoke("set-folder-view", v),
  setFolderDensity: (v) => ipcRenderer.invoke("set-folder-density", v),
  getFolderCounts: () => ipcRenderer.invoke("folder-counts"),
  getHistory: (q) => ipcRenderer.invoke("get-history", q || {}),
  clearHistory: () => ipcRenderer.invoke("clear-history"),
  reveal: (p) => ipcRenderer.invoke("reveal", p),
  openFolder: (name) => ipcRenderer.invoke("open-folder", name),
  openFile: (p) => ipcRenderer.invoke("open-file", p),
  openMainFolder: () => ipcRenderer.invoke("open-main-folder"),
  ensureSetup: () => ipcRenderer.invoke("ensure-setup"),
  pasteText: () => ipcRenderer.invoke("clipboard-read"),
  copyText: (text) => ipcRenderer.invoke("clipboard-write", text),
  deleteFile: (p, offerId) => ipcRenderer.invoke("delete-file", p, offerId),
  onProgress: (cb) => ipcRenderer.on("download-progress", (_e, p) => cb(p)),
  onSetupStatus: (cb) => ipcRenderer.on("setup-status", (_e, m) => cb(m)),

  // --- Feature 1: Queue ---
  queueGet: () => ipcRenderer.invoke("queue-get"),
  queueSet: (q) => ipcRenderer.invoke("queue-set", q),
  queueAdd: (items) => ipcRenderer.invoke("queue-add", items),
  queueClear: () => ipcRenderer.invoke("queue-clear"),
  queueClearFinished: () => ipcRenderer.invoke("queue-clear-finished"),
  queueRemoveErrors: () => ipcRenderer.invoke("queue-remove-errors"),
  queueRevealOutput: (id, p) => ipcRenderer.invoke("queue-reveal-output", id, p),
  queueLocateFile: (id) => ipcRenderer.invoke("queue-locate-file", id),
  queueAddOutputFolder: (id, p) => ipcRenderer.invoke("queue-add-output-folder", id, p),
  queueUpdateItem: (patch) => ipcRenderer.invoke("queue-update-item", patch),
  queueStart: () => ipcRenderer.invoke("queue-start"),
  queuePause: () => ipcRenderer.invoke("queue-pause"),
  queueStopAll: () => ipcRenderer.invoke("queue-stop-all"),
  queueCancel: () => ipcRenderer.invoke("queue-cancel"),
  queueStatus: () => ipcRenderer.invoke("queue-status"),
  onQueueChanged: (cb) => ipcRenderer.on("queue-changed", () => cb()),
  onQueueRun: (cb) => ipcRenderer.on("queue-run", () => cb()),
  onQueueIdle: (cb) => ipcRenderer.on("queue-idle", () => cb()),

  // --- Feature 2: Watch-folder ---
  watchGet: () => ipcRenderer.invoke("watch-get"),
  watchSet: (vals) => ipcRenderer.invoke("watch-set", vals),
  watchStart: () => ipcRenderer.invoke("watch-start"),
  watchStop: () => ipcRenderer.invoke("watch-stop"),

  // --- Feature 3: Fingerprint dedup ---
  fingerprintGetSettings: () => ipcRenderer.invoke("fingerprint-get-settings"),
  fingerprintSetEnabled: (v) => ipcRenderer.invoke("fingerprint-set-enabled", v),
  fingerprintSetThreshold: (v) => ipcRenderer.invoke("fingerprint-set-threshold", v),
  fingerprintRebuild: () => ipcRenderer.invoke("fingerprint-rebuild"),
  fingerprintDismiss: (offerId) => ipcRenderer.invoke("fingerprint-dismiss", offerId),
  onFingerprintDup: (cb) => ipcRenderer.on("fingerprint-dup", (_e, d) => cb(d)),
});
